export function formatRelativeTime(isoDate: string, lang: Lang): string {
  const date = new Date(isoDate);
  if (Number.isNaN(date.getTime())) return isoDate;
  const diffMins = Math.floor((Date.now() - date.getTime()) / 60000);
  const dict = TRANSLATIONS[lang];
  if (diffMins < 1) return dict.lv_now;
  if (diffMins < 60) return dict.lv_m.replace('%n', String(diffMins));
  const diffHours = Math.floor(diffMins / 60);
  if (diffHours < 24) return dict.lv_h.replace('%n', String(diffHours));
  const diffDays = Math.floor(diffHours / 24);
  if (diffDays < 30) return dict.lv_d.replace('%n', String(diffDays));
  const months = lang === 'en' ? MONTHS_EN : MONTHS_MS;
  return `${date.getDate()} ${months[date.getMonth()]} ${date.getFullYear()}`;
}
